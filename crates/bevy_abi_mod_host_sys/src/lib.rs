//! # Low-Level Host Runtime Internals for `bevy_abi_mod`
//!
//! `bevy_abi_mod_host_sys` isolates all `unsafe` host-side FFI bridges, [`UnsafeWorldCell`](bevy_ecs::world::unsafe_world_cell::UnsafeWorldCell)
//! chunk iteration, deferred raw [`OwningPtr`](bevy_ecs::ptr::OwningPtr) commands, dynamic `dlopen`/`dlsym`
//! management, and `extern "C"` trampolines behind safe internal helpers consumed by `bevy_abi_mod_host`.
//!
//! ## Subsystems
//! 1. **Dynamic Mod Lifecycle ([`host`])**:
//!    - Loads shared libraries via [`libloading`] with semver ABI handshake checks.
//!    - Enforces the atomic tombstone pattern ([`is_active: Arc<AtomicBool>`](host::LoadedMod::is_active))
//!      and schedule excision (`remove_systems_in_set`) to prevent executing unmapped code or leaking graph nodes.
//!    - Executes 4-phase clean shutdown in reverse load order (LIFO).
//! 2. **Component & Symbol Catalog ([`registry`])**:
//!    - Maps Bevy's non-deterministic runtime [`ComponentId`](bevy_ecs::component::ComponentId)s to
//!      deterministic 128-bit [`ComponentUuid`](bevy_abi_mod_sys::ComponentUuid)s and string names.
//!    - Stores static component VTables and field accessor functions generated by `ModExposable`.
//!    - Provides thread-local per-`World` isolated symbol resolution via [`host_get_proc_address`](registry::host_get_proc_address).
//! 3. **Dynamic System Adapter ([`dynamic_system`])**:
//!    - Adapts foreign C callbacks into native Bevy [`System`](bevy_ecs::system::System)s using
//!      Bevy's [`QueryBuilder`](bevy_ecs::query::QueryBuilder) and [`QueryState`](bevy_ecs::query::QueryState).
//!    - Supports both dense `Table` and `SparseSet` components/filters with zero data races.
//!    - Advances `world.increment_change_tick()` identically to native Bevy `FunctionSystem`s.
//! 4. **Zero-Allocation Chunk Iterator ([`chunk_iter`])**:
//!    - Directly traverses contiguous archetype table columns and sparse sets.
//!    - Enforces read vs write borrow permissions across the C boundary.
//!    - Automatically synchronizes Bevy change detection ticks on mutable column access.
//! 5. **Deferred Command Queue & Memory Isolation ([`commands`])**:
//!    - Synchronously allocates entity IDs via [`EntityAllocator`](bevy_ecs::entity::EntityAllocator).
//!    - Copies foreign component data into aligned host memory and forbids raw byte insertion onto
//!      heap-owning host components (`String`, `Vec`).

