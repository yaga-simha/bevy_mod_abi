//! # Component & Symbol Registry
//!
//! This module provides [`ModRegistry`], which acts as the central translation catalog
//! between Bevy's internal ECS types and the C-ABI mod interface.
//!
//! ## Architectural Responsibilities
//! 1. **Component ID Mapping**:
//!    - Bevy allocates [`ComponentId`] dynamically at runtime per [`World`].
//!    - Foreign mods cannot know these runtime IDs ahead of time.
//!    - [`ModRegistry`] indexes components by deterministic compile-time [`ComponentUuid`]
//!      (128-bit) and canonical string names, mapping them to runtime [`ComponentId`].
//! 2. **VTable & Accessor Storage**:
//!    - Stores static VTable pointers (`vtable_ptr`) and field accessor function pointers
//!      generated by `#[derive(ModExposable)]`.
//!    - Registers built-in engine bridge functions (`cmd_spawn_empty`, `cmd_despawn`,
//!      `cmd_insert_component`, `iter_reset`, `register_multi_query_system`,
//!      `register_system_in_schedule`, `register_component`).
//! 3. **Two-Tier Symbol Resolution ([`host_get_proc_address`])**:
//!    - **Tier 1 (Thread-Local Priority)**: Checks [`CURRENT_REGISTRY`]. Both mod initialization
//!      and system execution (`DynamicCSystem::run_unsafe`) bind [`CURRENT_REGISTRY`] on the
//!      executing worker thread, guaranteeing strict per-`World` symbol isolation on Bevy's
//!      multi-threaded executor.
//!    - **Tier 2 (Global Fallback)**: Checks [`GLOBAL_SYMBOLS`]. Enables resolution by
//!      standalone callers when no thread-local guard is active.
//! 4. **Safe Raw Deserialization (`insert_raw_impl`)**:
//!    - Only components without drop glue / heap pointers (`!core::mem::needs_drop::<T>()`)
//!      receive an `insert_raw_fn`. Components owning heap allocations (`String`, `Vec<T>`)
//!      leave `insert_raw_fn = None`, causing raw byte insertion attempts to return
//!      [`abi_contract::FfiResult::PERMISSION_DENIED`].

