//! # Host Runtime Bridge for `bevy_abi_mod`
//!
//! `host_runtime` bridges the Bevy ECS (v0.20+) world to native dynamic shared libraries
//! (`.so`, `.dylib`, `.dll`) compiled in Rust, C99, C++, or Zig over a stable, zero-serialization C-ABI.
//!
//! ## Architectural Overview
//! The crate is organized into five specialized subsystems:
//!
//! 1. **Dynamic Mod Lifecycle ([`host`])**:
//!    - Loads shared libraries via [`libloading`].
//!    - Performs handshake negotiation ([`bevy_abi_mod_init`](abi_contract::ModInitFn)) and version checks.
//!    - Enforces the atomic tombstone pattern ([`is_active: Arc<AtomicBool>`](host::LoadedMod::is_active))
//!      to prevent executing unmapped code after `dlclose`.
//!    - Executes 4-phase clean shutdown in reverse load order (LIFO).
//! 2. **Component & Symbol Catalog ([`registry`])**:
//!    - Maps Bevy's non-deterministic runtime [`ComponentId`](bevy_ecs::component::ComponentId)s to
//!      deterministic 128-bit [`ComponentUuid`](abi_contract::ComponentUuid)s and string names.
//!    - Stores static component VTables and field accessor functions generated by [`ModExposable`].
//!    - Provides two-tier symbol resolution via [`host_get_proc_address`](registry::host_get_proc_address)
//!      (thread-local isolated lookup prioritized over global fallback).
//! 3. **Dynamic System Adapter ([`dynamic_system`])**:
//!    - Adapts foreign C callbacks into native Bevy [`System`](bevy_ecs::system::System)s.
//!    - Dynamically builds [`FilteredAccessSet`](bevy_ecs::query::FilteredAccessSet) to integrate with
//!      Bevy's multi-threaded parallel scheduler without data races.
//!    - Validates intra-system query compatibility to prevent self-borrow conflicts.
//!    - Caches archetype tables via generation tracking, achieving zero heap allocations in steady-state.
//!    - Quarantines failing mods via panic containment ([`catch_unwind`](std::panic::catch_unwind)).
//! 4. **Zero-Allocation Chunk Iterator ([`chunk_iter`])**:
//!    - Directly traverses contiguous archetype table columns.
//!    - Enforces read vs write borrow permissions across the C boundary.
//!    - Automatically synchronizes Bevy change detection ticks on mutable column access.
//!    - Supports iterator rewinding for nested O(N*M) query systems.
//! 5. **Deferred Command Queue & Memory Isolation ([`commands`])**:
//!    - Synchronously allocates entity IDs via [`EntityAllocator`](bevy_ecs::entity::EntityAllocator).
//!    - Copies foreign component data into host memory to maintain strict dynamic allocator isolation.
//!    - Enqueues structural mutations into Bevy's [`CommandQueue`](bevy_ecs::world::CommandQueue).
//!
//! ## Quickstart
//!
//! ```rust,no_run
//! use bevy_app::{App, Update};
//! use host_runtime::prelude::*;
//!
//! let mut app = App::new();
//! app.add_plugins(AbiModPlugin::default());
//! // Register exposed components and load mods:
//! // app.register_mod_component::<Position>();
//! // app.load_mod("target/release/my_mod.dylib").expect("Failed to load mod");
//! ```

