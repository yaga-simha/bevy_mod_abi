fn push_component_section<T: ModComponentTrait>(out: &mut String) {
    out.push_str(&format!(
        "/* Component: `{}` (IS_ABI_POD = {}) */\n",
        T::CANONICAL_NAME,
        T::IS_ABI_POD
    ));
    out.push_str(T::C_DECL);
    out.push('\n');
}

/// Renders the deterministic C99 header `include/generated/testbed_components.h`.
pub fn generate_testbed_components_header() -> String {
    let mut out = String::with_capacity(12 * 1024);
    out.push_str("/*\n");
    out.push_str(
        " * ============================================================================\n",
    );
    out.push_str(
        " * AUTO-GENERATED BY `cargo xtask gen-component-headers` — DO NOT EDIT BY HAND.\n",
    );
    out.push_str(" *\n");
    out.push_str(
        " * Source of truth: `ModComponent::C_DECL` emitted by `#[derive(ModComponent)]`\n",
    );
    out.push_str(" * in `crates/bevy_abi_mod_macros`.\n");
    out.push_str(
        " * ============================================================================\n",
    );
    out.push_str(" */\n\n");
    out.push_str("#ifndef BEVY_ABI_MOD_GENERATED_TESTBED_COMPONENTS_H\n");
    out.push_str("#define BEVY_ABI_MOD_GENERATED_TESTBED_COMPONENTS_H\n\n");
    out.push_str("#include \"../bevy_abi_mod.h\"\n\n");
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

    push_component_section::<Position>(&mut out);
    push_component_section::<Velocity>(&mut out);
    push_component_section::<CombatHealth>(&mut out);
    push_component_section::<NameTag>(&mut out);
    push_component_section::<MetadataTag>(&mut out);
    push_component_section::<Mass>(&mut out);
    push_component_section::<Armor>(&mut out);
    push_component_section::<Phase4Transform>(&mut out);
    push_component_section::<Phase4CTransform>(&mut out);
    push_component_section::<Phase4Sensor>(&mut out);
    push_component_section::<Phase4CSensor>(&mut out);
    push_component_section::<Phase4FreshTag>(&mut out);
    push_component_section::<Phase4CFreshTag>(&mut out);
    push_component_section::<Phase4Removable>(&mut out);
    push_component_section::<Phase4CRemovable>(&mut out);
    push_component_section::<Phase4RustRes>(&mut out);
    push_component_section::<Phase4CRes>(&mut out);
    push_component_section::<Vec3>(&mut out);
    push_component_section::<CInteropComponent>(&mut out);

    out.push_str("#ifdef __cplusplus\n}\n#endif\n\n");
    out.push_str("#endif /* BEVY_ABI_MOD_GENERATED_TESTBED_COMPONENTS_H */\n");
    out
}

/// Writes `include/generated/testbed_components.h` or checks that it matches byte-for-byte.
pub fn write_or_check_component_headers(root: &Path, check_only: bool) -> Result<(), String> {
    let gen_dir = root.join("include").join("generated");
    let header_path = gen_dir.join("testbed_components.h");
    let expected = generate_testbed_components_header();

    if check_only {
        let existing_raw = fs::read_to_string(&header_path).map_err(|e| {
            format!(
                "missing {} ({e}); run `cargo xtask gen-component-headers`",
                header_path.display()
            )
        })?;
        let existing = existing_raw.replace("\r\n", "\n");
        if existing != expected {
            return Err(format!(
                "`{}` is out of date with `ModComponent::C_DECL`; run `cargo xtask gen-component-headers` and commit the result",
                header_path.display()
            ));
        }
        println!(
            "==> Verified `{}` matches `ModComponent::C_DECL` byte-for-byte",
            header_path.display()
        );
        return Ok(());
    }

    fs::create_dir_all(&gen_dir)
        .map_err(|e| format!("failed to create {}: {e}", gen_dir.display()))?;
    fs::write(&header_path, expected)
        .map_err(|e| format!("failed to write {}: {e}", header_path.display()))?;
    println!(
        "==> Wrote generated component header {}",
        header_path.display()
    );
    Ok(())
}
