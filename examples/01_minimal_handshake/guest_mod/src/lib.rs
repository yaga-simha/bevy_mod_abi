//! Example 1: Minimal Guest Mod (`minimal_guest_mod`)
#![deny(unsafe_op_in_unsafe_fn)]
#![deny(improper_ctypes_definitions)]

use core::ffi::c_void;
use guest_sdk::prelude::*;

#[repr(C)]
#[derive(Clone, Copy)]
pub struct PositionVTable {
    pub size: usize,
    pub align: usize,
    pub get_x: unsafe extern "C" fn(*const c_void) -> f32,
    pub set_x: unsafe extern "C" fn(*mut c_void, f32),
    pub get_y: unsafe extern "C" fn(*const c_void) -> f32,
    pub set_y: unsafe extern "C" fn(*mut c_void, f32),
    pub get_z: unsafe extern "C" fn(*const c_void) -> f32,
    pub set_z: unsafe extern "C" fn(*mut c_void, f32),
}

fn setup(app: &mut GuestApp<'_>) -> FfiResult {
    // SAFETY: `PositionVTable` matches the `#[repr(C)]` VTable layout generated by `#[derive(ModExposable)]` on the host.
    let Some(&vt) = (unsafe { app.resolve_vtable::<PositionVTable>(c"Position_vtable") }) else {
        return FfiResult::INVALID_COMPONENT;
    };

    let queries = [ComponentAccessDesc::write(c"Position".as_ptr())];
    app.add_system(c"PositionNudgeSystem", &queries, move |ctx| {
        while let Some(mut chunk) = ctx.iter().next_chunk_view() {
            let mut col = chunk.mutable_slice(0);
            if col.stride() != vt.size {
                return FfiResult::INTERNAL_ERROR;
            }
            for row in 0..col.count() {
                let Some(raw_ptr) = col.get_ptr_mut(row) else {
                    return FfiResult::NULL_POINTER;
                };
                let ptr = raw_ptr as *mut c_void;
                // SAFETY: `ptr` points to a valid `Position` element in column 0 for the current chunk row.
                unsafe {
                    let x = (vt.get_x)(ptr);
                    let y = (vt.get_y)(ptr);
                    let z = (vt.get_z)(ptr);
                    (vt.set_x)(ptr, x + 1.0);
                    (vt.set_y)(ptr, y + 2.0);
                    (vt.set_z)(ptr, z + 3.0);
                }
            }
        }
        FfiResult::OK
    })
}

export_mod!(setup);
