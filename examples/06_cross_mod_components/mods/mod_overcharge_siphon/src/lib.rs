//! Mod B: Overcharge Siphon Mod (`mod_overcharge_siphon`)
//!
//! Demonstrates:
//! 1. Inter-mod dynamic component query: Mod B queries `EnergyShield` by name.
//! 2. Zero component introduction: Mod B does NOT register `EnergyShield` (never calls
//!    `register_runtime_component`) and did NOT spawn the entities.
//! 3. Hardware-speed access: Iterates archetype chunks, reads `EnergyShield` components
//!    introduced by Mod A, siphons energy (-12.0 MW), and mutates the data in-place without
//!    any serialization or host allocator crossover.

#![deny(unsafe_op_in_unsafe_fn)]

use core::ffi::c_void;
use core::sync::atomic::{AtomicPtr, Ordering};
use guest_sdk::prelude::*;

/// C-ABI layout mirror of `EnergyShield` introduced by Mod A.
/// Notice that Mod B does not share a Rust crate dependency with Mod A;
/// it simply shares the `#[repr(C)]` layout specification.
#[derive(Clone, Copy, Debug, PartialEq)]
#[repr(C)]
pub struct EnergyShield {
    pub current: f32,
    pub max: f32,
    pub frequency_mhz: u32,
}

static HOST_API: AtomicPtr<HostApi> = AtomicPtr::new(core::ptr::null_mut());

/// System: Siphon and Overcharge Collector
///
/// Queries `EnergyShield` (WRITE access) across all matching archetypes.
/// Siphons power from active shields generated by Mod A to power grid reserves.
unsafe fn shield_siphon_system(
    iter: *mut RawChunkIter,
    _commands: *mut RawCommandQueue,
    _user_data: *mut c_void,
) -> FfiResult {
    let api_ptr = HOST_API.load(Ordering::Acquire);
    if api_ptr.is_null() || iter.is_null() {
        return FfiResult::INTERNAL_ERROR;
    }
    let api = unsafe { &*api_ptr };
    let mut chunk_iter = GuestChunkIter::new(iter, api);

    loop {
        let count = chunk_iter.next_chunk();
        if count == 0 {
            break;
        }

        // Direct typed slice access over the contiguous Bevy archetype table column
        let mut slice = chunk_iter.mutable_slice(0, count);
        let Some(shields) = slice.as_typed_slice::<EnergyShield>() else {
            return FfiResult::INTERNAL_ERROR;
        };

        for (row, shield) in shields.iter_mut().enumerate() {
            let before = shield.current;
            // Siphon 12.0 MW from the shield
            let drain = 12.0f32.min(shield.current);
            shield.current -= drain;

            println!(
                "  [Mod B::siphon]   Foreign Drone row #{} at {} MHz: Siphoned {:.1} MW ({:.1} -> {:.1} MW remaining)",
                row + 1,
                shield.frequency_mhz,
                drain,
                before,
                shield.current
            );
        }
    }

    FfiResult::OK
}

wrap_system_callback!(fn c_shield_siphon calls shield_siphon_system);

fn mod_init(
    _get_proc_address: GetProcAddressFn,
    host_api: *const HostApi,
    host_context: *mut c_void,
) -> FfiResult {
    if host_api.is_null() || host_context.is_null() {
        return FfiResult::NULL_POINTER;
    }
    HOST_API.store(host_api as *mut HostApi, Ordering::Release);

    let api = unsafe { &*host_api };

    // Notice: Mod B does NOT call register_runtime_component!
    // It directly registers a system querying "EnergyShield", which was introduced by Mod A.
    let queries = [ComponentAccessDesc {
        name: c"EnergyShield".as_ptr(),
        mode: ComponentAccessMode::WRITE,
    }];

    let siphon_desc = SystemDescriptor {
        struct_size: core::mem::size_of::<SystemDescriptor>() as u32,
        name: c"shield_siphon_system".as_ptr(),
        queries: queries.as_ptr(),
        query_count: queries.len(),
        callback: c_shield_siphon,
        user_data: core::ptr::null_mut(),
    };

    unsafe { (api.register_system)(host_context, &siphon_desc) }
}

fn mod_shutdown(_host_context: *mut c_void) -> FfiResult {
    HOST_API.store(core::ptr::null_mut(), Ordering::Release);
    FfiResult::OK
}

export_mod!(mod_init, mod_shutdown);
